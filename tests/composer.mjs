import assert from "node:assert/strict";
import {mkdir} from "node:fs/promises";
import {chromium} from "playwright";
import {scheduledInstant} from "../composer.mjs";

assert.equal(scheduledInstant("2026-11-06","18:00","America/Sao_Paulo"),"2026-11-06T21:00:00.000Z");
assert.equal(scheduledInstant("2026-02-31","18:00","America/Sao_Paulo"),null);
assert.equal(scheduledInstant("2026-03-08","02:30","America/New_York"),null);
assert.equal(scheduledInstant("2026-11-01","01:30","America/New_York"),null);
const base = new URL(process.env.STUDIO_URL??"http://127.0.0.1:3021");
const demo = new URL("?demo=1#agenda",base);
const b = await chromium.launch();
await mkdir("test-results/layout",{recursive:true});
try {
  const p = await b.newPage({viewport:{width:1366,height:768},reducedMotion:"reduce"});
  const errors=[];
  p.on("pageerror",e=>errors.push(e.message));
  await p.goto(demo.href);
  const image = await p.evaluate(()=>{
    const canvas=document.createElement("canvas");
    canvas.width=480;canvas.height=600;
    const context=canvas.getContext("2d");
    context.fillStyle="#ded0ba";context.fillRect(0,0,480,600);
    context.fillStyle="#4c5848";context.beginPath();context.arc(275,310,156,0,Math.PI*2);context.fill();
    context.fillStyle="#c87650";context.beginPath();context.arc(130,420,108,0,Math.PI*2);context.fill();
    return canvas.toDataURL("image/png").split(",")[1];
  });
  const file = name=>({name,mimeType:"image/png",buffer:Buffer.from(image,"base64")});
  const open = p.locator("#agenda-new");
  const dialog = p.getByRole("dialog",{name:"Nova publicação"});
  const next = dialog.locator('[data-composer-action="next"]');
  const capture = n=>p.screenshot({path:`test-results/layout/composer-etapa-${n}.png`});
  await open.click();
  assert.equal(await dialog.getByRole("button",{name:/Facebook/}).isDisabled(),true);
  assert.equal(await next.isDisabled(),true);
  await dialog.getByRole("button",{name:/Instagram/}).click();
  await capture(1);
  await next.click();
  const client = dialog.getByRole("combobox",{name:"Cliente",exact:true});
  const account = dialog.getByRole("combobox",{name:"Conta do Instagram"});
  assert.equal(await client.locator('option[value="forma-lab"]').count(),0);
  await client.selectOption("aurora-studio");
  await account.selectOption("aurora");
  await client.selectOption("casanova");
  assert.equal(await account.inputValue(),"");
  assert.equal(await account.locator('option[value="aurora"]').count(),0);
  await client.selectOption("aurora-studio");
  await account.selectOption("aurora");
  await capture(2);
  await next.click();
  await dialog.getByRole("button",{name:/Carrossel/}).click();
  await dialog.getByRole("combobox",{name:"Categoria editorial"}).selectOption("Educativo");
  const compact=(await dialog.boundingBox()).width;
  await capture(3);
  await next.click();
  assert.ok((await dialog.boundingBox()).width>compact);
  await next.click();
  assert.match(await dialog.getByRole("status").last().innerText(),/2 a 10/);
  await dialog.getByLabel("Adicionar mídia").setInputFiles({name:"erro.txt",mimeType:"text/plain",buffer:Buffer.from("x")});
  assert.match(await dialog.getByRole("status").last().innerText(),/incompatível/);
  await dialog.getByLabel("Adicionar mídia").setInputFiles([file("primeira.png"),file("segunda.png")]);
  await dialog.getByRole("button",{name:"Mover mídia 2 para cima"}).click();
  assert.match(await dialog.locator(".composer-media-list li").first().innerText(),/segunda/);
  await dialog.getByRole("button",{name:"Próxima mídia"}).click();
  assert.equal(await dialog.getByAltText("Prévia da mídia 2").count(),1);
  await p.waitForFunction(()=>document.querySelector(".composer-preview-media img")?.naturalWidth===480);
  await dialog.getByLabel("Título interno").fill("Coleção de teste");
  await dialog.getByLabel("Legenda").fill("Primeira linha\n#socialstudio");
  assert.equal(await dialog.locator(".composer-preview-caption").textContent(),"Primeira linha\n#socialstudio");
  await capture(4);
  await next.click();
  await dialog.getByRole("button",{name:/Agendar na demonstração/}).click();
  await dialog.getByLabel("Horário",{exact:true}).fill("07:30");
  await next.click();
  assert.match(await dialog.getByRole("status").last().innerText(),/horário futuro/);
  await dialog.getByLabel("Horário",{exact:true}).fill("18:00");
  await capture(5);
  await next.click();
  assert.match(await dialog.locator(".composer-review").innerText(),/@aurora\.studio/);
  await capture(6);
  await next.click();
  await dialog.getByRole("heading",{name:"Agendamento de demonstração registrado"}).waitFor();
  await dialog.getByRole("button",{name:"Ver na Agenda"}).click();
  assert.equal(await p.locator('#agenda [data-agenda-event]').filter({hasText:"Coleção de teste"}).count(),1);
  await open.click();
  await dialog.getByRole("button",{name:/Instagram/}).click();
  await next.click();
  await client.selectOption("aurora-studio");
  await account.selectOption("aurora");
  await next.click();
  await dialog.getByRole("button",{name:/Feed/}).click();
  await next.click();
  await dialog.getByLabel("Adicionar mídia").setInputFiles(file("rascunho.png"));
  await dialog.getByLabel("Legenda").fill("Legenda recuperável");
  await p.keyboard.press("Escape");
  await dialog.waitFor({state:"hidden"});
  assert.equal(await open.evaluate(el=>el===document.activeElement),true);
  await p.reload();
  await open.click();
  await dialog.getByRole("button",{name:"Retomar"}).click();
  await next.click();
  assert.equal(await account.inputValue(),"aurora");
  await next.click();
  await next.click();
  assert.equal(await dialog.getByLabel("Legenda").inputValue(),"Legenda recuperável");
  assert.match(await dialog.locator(".composer-media-list").innerText(),/rascunho.png/);
  assert.deepEqual(errors,[]);
  await p.close();
  for(const [width,height] of [[390,844],[768,1024],[1024,768],[1440,900],[1920,1080],[3440,1440]]) {
    const page=await b.newPage({viewport:{width,height},reducedMotion:"reduce"});
    await page.goto(demo.href);
    await page.getByRole("switch",{name:"Modo escuro"}).click();
    await page.locator("#agenda-new").click();
    const modal=page.locator("#composer");
    const rect=await modal.boundingBox();
    assert.ok(rect.x>=0&&rect.y>=0&&rect.x+rect.width<=width&&rect.y+rect.height<=height);
    if(width===390) await page.screenshot({path:"test-results/layout/composer-mobile-dark.png"});
    await page.close();
  }
  const live=await b.newPage();
  await live.goto(new URL("#agenda",base).href);
  await live.locator("#agenda-new").click();
  assert.equal(await live.locator('#composer [data-platform-choice="instagram"]').isDisabled(),true);
  await live.close();
  console.log("Compositor: seis etapas, escopo, mídia, prévia, datas, Agenda, rascunho e responsividade verificados.");
} finally {await b.close();}
