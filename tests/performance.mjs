import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";

const base = process.env.STUDIO_URL ?? "http://127.0.0.1:3021";
const browser = await chromium.launch();
const errors = [];
await mkdir("test-results/performance",{recursive:true});
try {
  for (const [width,height] of [[1366,768],[1920,1080],[390,844],[375,812]]) {
    const page = await browser.newPage({viewport:{width,height}});
    page.on("pageerror",error => errors.push(error.message));
    await page.goto(base + "/?demo=1#performance");
    await page.evaluate(() => document.fonts.ready);
    assert.match(await page.locator("#performance").evaluate(node => getComputedStyle(node).fontFamily),/Geist Sans/);
    assert.equal(await page.locator(".perf-kpis .metric").count(),4);
    assert.equal(await page.locator(".perf-kpi .widget-help").count(),6);
    const originalReach = await page.locator(".perf-kpis .perf-kpi-value").first().textContent();
    assert.equal(await page.locator("[data-perf-period]").count(),0);
    await page.locator("#perf-filter-trigger").click();
    await page.getByRole("radio",{name:"Últimos 30 dias",exact:true}).check();
    await page.getByRole("button",{name:"Aplicar filtros",exact:true}).click();
    assert.equal(new URL(page.url()).searchParams.get("period"),"30");
    assert.notEqual(await page.locator(".perf-kpis .perf-kpi-value").first().textContent(),originalReach);
    const chart = page.locator("#perf-views .perf-chart");
    await chart.focus();
    await page.keyboard.press("Home");
    const firstTip = await chart.locator(".perf-tip").textContent();
    await page.keyboard.press("End");
    assert.notEqual(await chart.locator(".perf-tip").textContent(),firstTip);
    await page.keyboard.press("Escape");
    assert.equal(await chart.locator(".perf-tip").isVisible(),false);
    await page.getByRole("button",{name:"Sobre Alcance",exact:true}).click();
    assert.equal(await page.locator("#perf-kpi-users-round-help").isVisible(),true);
    await page.keyboard.press("Escape");
    assert.equal(await page.locator("#perf-kpi-users-round-help:popover-open").count(),0);
    await page.locator("#perf-audience").getByRole("button",{name:"@aurora.studio",exact:true}).click();
    assert.equal(new URL(page.url()).searchParams.get("account"),"aurora");
    assert.equal(await page.locator(".perf-ages li").count(),7);
    await page.getByRole("radio",{name:"Engajados",exact:true}).click();
    assert.equal(await page.getByRole("radio",{name:"Engajados",exact:true}).getAttribute("aria-checked"),"true");
    const contents = page.locator("#perf-content");
    await contents.getByRole("radio",{name:"Stories",exact:true}).click();
    assert.ok((await contents.locator("tbody tr").count()) > 0);
    assert.ok((await contents.locator(".perf-type").allTextContents()).every(text => text === "Stories"));
    await page.getByRole("combobox",{name:"Ordenar publicações por"}).selectOption("views");
    assert.equal(await contents.locator("th[aria-sort=descending]").textContent(),"Visualizações ↓");
    assert.ok(await page.locator(".workspace").evaluate(node => node.scrollWidth <= node.clientWidth+1));
    assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight+1));
    await page.screenshot({path:`test-results/performance/content-${width}.png`});
    await page.locator("#performance-title").scrollIntoViewIfNeeded();
    await page.screenshot({path:`test-results/performance/desktop-${width}.png`});
    await page.getByRole("switch",{name:"Modo escuro"}).click();
    await page.mouse.move(0,0);
    await page.screenshot({path:`test-results/performance/dark-${width}.png`});
    assert.equal(await page.locator("html").getAttribute("data-theme"),"dark");
    await page.emulateMedia({reducedMotion:"reduce"});
    await page.getByRole("button",{name:"Expandir menu",exact:true}).isVisible().then(async visible => { if (visible) await page.getByRole("button",{name:"Expandir menu",exact:true}).click(); });
    assert.ok(await page.locator(".workspace").evaluate(node => node.scrollWidth <= node.clientWidth+1));
    await page.close();
    console.log(`${width}px: filtros, gráficos por teclado, ajuda, público, conteúdos, temas e overflow verificados.`);
  }
  const page = await browser.newPage();
  page.on("pageerror",error => errors.push(error.message));
  await page.goto(base + "/?demo=1#performance");
  await page.locator("#perf-filter-trigger").click();
  assert.equal(await page.locator("#filter-panel:popover-open").count(),1);
  await page.locator("#client-toggle").click();
  await page.locator('#client-options input[value="aurora-studio"]').check();
  await page.locator("#account-toggle").click();
  await page.locator('#account-options input[value="aurora"]').check();
  await page.getByRole("radio",{name:"Últimos 7 dias",exact:true}).check();
  await page.getByRole("button",{name:"Aplicar filtros",exact:true}).click();
  assert.equal(new URL(page.url()).searchParams.get("account"),"aurora");
  assert.equal(new URL(page.url()).searchParams.get("period"),"7");
  assert.equal(await page.locator(".perf-nav,#perf-overview-title,#perf-scope").count(),0);
  await page.goto(base + "/?demo=1&period=custom&start=2026-11-07&end=2026-11-07#performance");
  assert.match(await page.locator("#perf-interactions").textContent(),/Interações indisponíveis/);
  assert.equal(await page.locator("#perf-views .perf-bar-row").count(),0);
  await page.goto(base + "/#performance");
  assert.equal(await page.locator("#performance .perf-kpi").count(),0);
  assert.match(await page.locator("#performance-summary").textContent(),/Sem fonte conectada/);
  assert.equal(await page.locator("#performance .perf-empty").count(),6);
  assert.deepEqual(errors,[]);
  console.log("Histórico ausente e ausência de fonte real preservam estados indisponíveis.");
} finally {
  await browser.close();
}
